// Writes docs/CONFIG.md (repo root) from the zod schema in src/main/envSpec.ts and the task usage
// in src/main/tasks/args.ts, so the docs can't drift from the code.
//   node scripts/config-docs.mjs          rewrite the file
//   node scripts/config-docs.mjs --check  exit 1 if it is out of date (CI)
// envSpec.ts is loaded with Node's type stripping (Node 22.18+); it imports only node:path and zod.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const { EnvVars } = await import('../src/main/envSpec.ts')
// Each variable's docs are the zod schema's metadata (`.meta()`), so they live next to its check.
const ENV_VARS = Object.entries(EnvVars.shape).map(([name, schema]) => ({ name, ...schema.meta() }))
const target = join(here, '../../../docs/CONFIG.md')

// The usage block at the top of tasks/args.ts is the reference for task options.
const argsSource = readFileSync(join(here, '../src/main/tasks/args.ts'), 'utf8')
const usage = /\/\*\*\n \* One-off tasks[^\n]*\n \*\n([\s\S]*?) \*\n/.exec(argsSource)?.[1]
if (!usage) throw new Error('could not find the task usage block in src/main/tasks/args.ts')
const usageLines = usage
  .split('\n')
  .filter(Boolean)
  .map((line) => line.replace(/^ \* {3}/, ''))

const cell = (text) => text.replaceAll('|', '\\|')
const doc = `# Configuration

Generated by \`pnpm config:docs\` from \`apps/lyra/src/main/envSpec.ts\` and
\`apps/lyra/src/main/tasks/args.ts\`. Do not edit by hand; CI fails when it is out of date.

Lyra is configured in its Settings window. The environment variables below are for setups the
window doesn't cover: a shared models folder, a mirror, keys from a secrets manager, a proxy.
They are read once at startup. A value that is set but malformed stops Lyra with a message naming
the variable; an empty value is the same as unset. Names follow the tool that defined them
(the AI SDK providers, Hugging Face) where there is one, so a machine already set up for those works
as is; only Lyra's own settings take the \`LYRA_\` prefix.

Lyra reads the process environment, not a \`.env\` file.

| Variable | Kind | What it does | When unset |
| --- | --- | --- | --- |
${ENV_VARS.map((v) => `| \`${v.name}\` | ${v.kind} | ${cell(v.description)} | ${cell(v.fallback)} |`).join('\n')}

Paths must be absolute. URLs must be \`http\` or \`https\`. Secrets are never written to the log;
the startup line lists which variables are set, not their values.

## One-off tasks

Smoke tests, screenshots and meeting replays run through the same binary as the app, chosen on
the command line. Each runs in a throwaway profile and exits with its result. In development the
\`pnpm\` scripts launch them (\`smoke:ui\`, \`screenshot\`, \`smoke:meeting\`, \`eval:*\`,
\`replay:session\`).

\`\`\`text
${usageLines.join('\n')}
\`\`\`
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8').replaceAll('\r\n', '\n')
  } catch {
    // Missing counts as out of date.
  }
  if (current !== doc) {
    console.error('docs/CONFIG.md is out of date; run `pnpm config:docs` and commit the result.')
    process.exit(1)
  }
  console.log('docs/CONFIG.md is up to date')
} else {
  writeFileSync(target, doc)
  console.log(`wrote ${target}`)
}
