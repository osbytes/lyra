// Copies the desktop app's stylesheet into the website, scoped under `.lyra-ui`, so the demo is
// drawn with the app's real styles and can't drift from them. Runs before `next dev` and
// `next build`; the output is gitignored.
//
// `:root` becomes `.lyra-ui`, so the app's tokens only apply inside the demo. Rules that only make
// sense in an Electron window (the full-height body, window dragging, the overlay pill window) are
// dropped.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const SOURCE = join(here, '../../lyra/src/renderer/src/assets/styles.css')
const TARGET = join(here, '../components/demo/app-styles.generated.css')
const SCOPE = '.lyra-ui'
const DROP = [/^html\b/, /^body\b/, /#root\b/, /\.is-overlay\b/, /\.overlay-/, /\.platform-/, /^\.(no-)?drag$/]
const PASS_THROUGH = ['@keyframes', '@font-face']
const NESTED = ['@media', '@container', '@supports']

/** Splits on `separator` outside parentheses, so `:is(a, b)` stays one selector. */
function splitTopLevel(text, separator) {
  const parts = []
  let depth = 0
  let start = 0
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]
    if (ch === '(') depth++
    else if (ch === ')') depth--
    else if (ch === separator && depth === 0) {
      parts.push(text.slice(start, i))
      start = i + 1
    }
  }
  parts.push(text.slice(start))
  return parts.map((part) => part.trim()).filter(Boolean)
}

/** Top-level `prelude { body }` blocks. */
function parse(css) {
  const blocks = []
  let i = 0
  while (i < css.length) {
    const open = css.indexOf('{', i)
    if (open === -1) break
    let depth = 1
    let j = open + 1
    while (j < css.length && depth > 0) {
      if (css[j] === '{') depth++
      else if (css[j] === '}') depth--
      j++
    }
    blocks.push({ prelude: css.slice(i, open).trim(), body: css.slice(open + 1, j - 1) })
    i = j
  }
  return blocks
}

function scope(selector) {
  return selector === ':root' ? SCOPE : `${SCOPE} ${selector}`
}

function transform(css) {
  const out = []
  for (const { prelude, body } of parse(css)) {
    if (PASS_THROUGH.some((at) => prelude.startsWith(at))) {
      out.push(`${prelude} {${body}}`)
    } else if (NESTED.some((at) => prelude.startsWith(at))) {
      const inner = transform(body)
      if (inner) out.push(`${prelude} {\n${inner}\n}`)
    } else {
      const selectors = splitTopLevel(prelude, ',').filter((s) => !DROP.some((re) => re.test(s)))
      if (!selectors.length) continue
      const declarations = body.replace(/-webkit-app-region\s*:[^;]*;?/g, '').trim()
      out.push(`${selectors.map(scope).join(',\n')} {\n  ${declarations}\n}`)
    }
  }
  return out.join('\n\n')
}

const source = readFileSync(SOURCE, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')
const header =
  '/* Generated by apps/website/scripts/sync-app-styles.mjs from\n' +
  ' * apps/lyra/src/renderer/src/assets/styles.css. Do not edit. */\n\n'
mkdirSync(dirname(TARGET), { recursive: true })
writeFileSync(TARGET, `${header}${transform(source)}\n`)
console.log(`sync-app-styles: wrote ${TARGET}`)
